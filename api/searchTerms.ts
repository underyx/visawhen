// Words people search the list pages with that are not in the data: what
// people call a USCIS form ("work permit", "green card"), and which country a
// consulate is in ("Mexico" finds Ciudad Juarez, where Mexico's immigrant
// visas are issued, as well as Mexico City). Hand-maintained here rather than
// in forms.json or the consulate tables, which the scrapers regenerate.

