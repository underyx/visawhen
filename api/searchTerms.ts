/** Fails the build when a post in the data has no country in POST_COUNTRIES,
 * so that a post State adds gets one. */
export function checkPostCountries(postSlugs: string[]): void {
  const missing = postSlugs.filter((slug) => !(slug in POST_COUNTRIES));
  if (missing.length > 0)
    throw new Error(
      `api/searchTerms.ts: POST_COUNTRIES has no country for ${missing.join(
        ", ",
      )}`,
    );
}
